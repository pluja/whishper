KNOWN_CODES = frozenset(WHISPER_LANGUAGE_CODES.values())


def language_code(reported: str | None) -> str | None:
    """Maps the language a speech API reports, a code or a Whisper name, to its code."""
    if not reported:
        return None
    value = reported.strip().lower()
    if value in KNOWN_CODES:
        return value
    return WHISPER_LANGUAGE_CODES.get(value)
