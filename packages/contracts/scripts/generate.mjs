import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";
import { format } from "prettier";

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
export const SCHEMA_PATH = join(packageRoot, "schema", "protocol.schema.json");
export const GENERATED_DIRECTORY = join(packageRoot, "src", "generated");

const banner = (tool) =>
  `// Generated by packages/contracts/scripts/generate.mjs with ${tool} from
// schema/protocol.schema.json, which the worker exports from its Pydantic models.
// Do not edit. Run \`make generate\` instead.
`;

function constantName(definitionName) {
  return definitionName.replace(/(?<=[a-z0-9])(?=[A-Z])/g, "_").toUpperCase();
}

async function generateTypes(schema) {
  const types = await compile(schema, schema.title, {
    additionalProperties: false,
    bannerComment: "",
    format: false,
    unreachableDefinitions: true,
  });
  const constants = Object.entries(schema.$defs)
    .filter(([, definition]) => typeof definition.const === "string")
    .map(
      ([name, definition]) =>
        `export const ${constantName(name)} = ${JSON.stringify(definition.const)};`,
    );
  return [banner("json-schema-to-typescript"), types, ...constants].join("\n");
}

function messageNames(schema) {
  return schema.anyOf.map(({ $ref }) => $ref.replace("#/$defs/", ""));
}

const UNICODE_DEPRECATION = /^DEPRECATED: option unicode\./;

const ajvLogger = {
  log: (...message) => console.log(...message),
  warn: (...message) => {
    if (!UNICODE_DEPRECATION.test(String(message[0]))) console.warn(...message);
  },
  error: (...message) => console.error(...message),
};

function generateValidators(schema) {
  const ajv = new Ajv2020({
    code: { source: true, esm: true },
    allErrors: true,
    inlineRefs: false,
    strict: true,
    // String lengths count UTF-16 units, so the generated code needs no runtime
    // import from ajv. The option is deprecated but honoured throughout ajv 8,
    // so the logger drops only that deprecation notice.
    unicode: false,
    logger: ajvLogger,
  });
  ajv.addSchema(schema, "protocol");
  const exports = Object.fromEntries(
    messageNames(schema).map((name) => [
      `validate${name}`,
      `protocol#/$defs/${name}`,
    ]),
  );
  return `${banner("ajv standalone")}${standaloneCode(ajv, exports)}`;
}

function generateValidatorDeclarations(schema) {
  const names = messageNames(schema);
  return `${banner("ajv standalone")}
import type { ${names.join(", ")} } from "./protocol";

export type ProtocolValidationError = {
  instancePath: string;
  keyword: string;
  message?: string;
  params: Record<string, unknown>;
};

export type ProtocolValidator<T> = ((value: unknown) => value is T) & {
  errors?: ProtocolValidationError[] | null;
};

${names
  .map(
    (name) =>
      `export declare const validate${name}: ProtocolValidator<${name}>;`,
  )
  .join("\n")}
`;
}

export async function generateProtocolSources() {
  const schema = JSON.parse(await readFile(SCHEMA_PATH, "utf8"));
  const sources = {
    "protocol.ts": await generateTypes(schema),
    "validators.js": generateValidators(schema),
    "validators.d.ts": generateValidatorDeclarations(schema),
  };
  return Object.fromEntries(
    await Promise.all(
      Object.entries(sources).map(async ([fileName, source]) => [
        fileName,
        await format(source, {
          filepath: join(GENERATED_DIRECTORY, fileName),
        }),
      ]),
    ),
  );
}

if (import.meta.main) {
  await mkdir(GENERATED_DIRECTORY, { recursive: true });
  for (const [fileName, source] of Object.entries(
    await generateProtocolSources(),
  )) {
    await writeFile(join(GENERATED_DIRECTORY, fileName), source);
  }
}
