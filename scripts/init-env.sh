#!/bin/sh
# Create a .env file from .env.example with generated secrets.
#
# Anysub refuses to start with the change-this placeholders from .env.example.
# Run this once before the first `docker compose up`.

set -eu

repository_root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
template="$repository_root/.env.example"
env_file="$repository_root/.env"

if [ -e "$env_file" ]; then
  echo "$env_file already exists. Remove it first if you want new secrets." >&2
  echo "Rotating BETTER_AUTH_SECRET signs existing sessions out." >&2
  exit 1
fi

# Restrict to URL-safe characters so DATABASE_URL can carry the password
# without escaping. 48 bytes give 64 characters, above every minimum length.
random_token() {
  head -c 48 /dev/urandom | base64 | tr '+/' '-_' | tr -d '=\n'
}

umask 077
staging=$(mktemp "$env_file.XXXXXX")
trap 'rm -f "$staging"' EXIT

{
  echo "# Generated by scripts/init-env.sh from .env.example. Keep this file out of version control."
  while IFS= read -r line || [ -n "$line" ]; do
    case $line in
      [A-Z_]*=change-this-*) printf '%s=%s\n' "${line%%=*}" "$(random_token)" ;;
      *) printf '%s\n' "$line" ;;
    esac
  done <"$template"
} >"$staging"

mv "$staging" "$env_file"

echo "Wrote $env_file with generated secrets."
echo "Set BETTER_AUTH_URL to the browser-facing origin before exposing Anysub."
