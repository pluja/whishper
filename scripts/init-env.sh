#!/bin/sh
# Create a .env file with generated secrets.
#
# Anysub refuses to start with the placeholder values in .env.example. Run this
# once before the first `docker compose up`.

set -eu

repository_root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
env_file="$repository_root/.env"

if [ -e "$env_file" ]; then
  echo "$env_file already exists. Remove it first if you want new secrets." >&2
  echo "Rotating BETTER_AUTH_SECRET signs existing sessions out." >&2
  exit 1
fi

# Restrict to URL-safe characters so DATABASE_URL can carry the password
# without escaping.
random_token() {
  head -c "$1" /dev/urandom | base64 | tr '+/' '-_' | tr -d '=\n'
}

umask 077
cat >"$env_file" <<EOF
# Generated by scripts/init-env.sh. Keep this file out of version control.
POSTGRES_DB=anysub
POSTGRES_USER=anysub
POSTGRES_PASSWORD=$(random_token 32)

# Signs session cookies. Changing it signs every account out.
BETTER_AUTH_SECRET=$(random_token 48)

# The browser-facing origin, including a non-default port. Set this to the
# public URL when Anysub runs behind a reverse proxy.
BETTER_AUTH_URL=http://localhost:5173

# Shared by the application and its workers.
ANYSUB_WORKER_TOKEN=$(random_token 32)

# Browser-facing application port.
ANYSUB_PORT=5173

# Maximum size of one resumable browser upload (default: 500 GiB).
ANYSUB_MAX_UPLOAD_BYTES=536870912000

# Per-request SvelteKit limit. Must remain larger than the 32 MiB tus chunk.
ANYSUB_BODY_SIZE_LIMIT=64M
EOF

echo "Wrote $env_file with generated secrets."
echo "Set BETTER_AUTH_URL to the browser-facing origin before exposing Anysub."
